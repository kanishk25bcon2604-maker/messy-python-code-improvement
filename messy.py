SKIPPED_ITEMS = 1

values = [0, 80, 70, 90]


def average_excluding_first(items):
    """Return the average of all items after the first (skipped) element."""
    total = 0
    for index in range(SKIPPED_ITEMS, len(items)):
        total = total + items[index]
    return total / (len(items) - SKIPPED_ITEMS)


def count_above_average(items, class_average):
    """Return how many scores after the first (skipped) element exceed class_average."""
    above_average_total = 0
    for index in range(SKIPPED_ITEMS, len(items)):
        if items[index] > class_average:
            above_average_total = above_average_total + 1
    return above_average_total


average = average_excluding_first(values)
above_average_count = count_above_average(values, average)

print(f"Average: {average}")
print(f"Above average: {above_average_count}")
